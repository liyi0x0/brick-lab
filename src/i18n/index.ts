export type TKey = keyof typeof zh;

const dicts: Record<Lang, Dict> = { zh, en };

export function tr(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? zh[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** React hook：返回当前语言的翻译函数 */
export function useT() {
  const lang = useStore((s) => s.settings.lang);
  return (key: TKey, params?: Record<string, string | number>) => tr(lang, key, params);
}

export function useLang() {
  return useStore((s) => s.settings.lang);
}
